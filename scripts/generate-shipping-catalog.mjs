import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../src/WorkspaceEcommerce.Infrastructure/Shipping/Data/vietnam-administrative-catalog.json", import.meta.url);
const target = new URL("../frontend/apps/storefront/src/constants/vietnamAdministrativeUnits.ts", import.meta.url);
const bytes = readFileSync(source);
const catalog = JSON.parse(bytes);
const provinces = new Set();
const wards = new Set();
for (const province of catalog.provinces) {
  if (!/^\d{2}$/.test(province.code) || provinces.has(province.code) || !province.wards.length)
    throw new Error("Invalid province code/coverage.");
  provinces.add(province.code);
  for (const ward of province.wards) {
    if (!/^\d{5}$/.test(ward.code) || wards.has(ward.code)) throw new Error("Invalid/duplicate ward code.");
    wards.add(ward.code);
  }
}
const generated = `// Generated by scripts/generate-shipping-catalog.mjs. Edit the canonical JSON, then regenerate.
// Catalog: ${catalog.version}; SHA-256: ${createHash("sha256").update(bytes).digest("hex")}
export interface VietnamWard { code: string; name: string; }
export interface VietnamProvince { code: string; name: string; wards: VietnamWard[]; }
export const VIETNAM_ADMINISTRATIVE_CATALOG_VERSION = ${JSON.stringify(catalog.version)};
export const VIETNAM_ADMINISTRATIVE_UNITS: VietnamProvince[] = ${JSON.stringify(catalog.provinces, null, 2)};
`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Shipping catalog artifact is stale; regenerate it.");
  process.stdout.write("Shipping administrative catalog artifact is current.\n");
} else {
  writeFileSync(fileURLToPath(target), generated);
  process.stdout.write("Generated storefront catalog from the backend canonical source.\n");
}
